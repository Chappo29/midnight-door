/**
 * Эмодзи в тексте — на старых системах (Windows 7, старые Android) вместо них квадраты (правила Яндекса 1.14, 1.20).
 * Всё, что приходит в подписи снаружи, проходит через stripEmoji: вместо значка в игре — картинки и цвет.
 */
const EMOJI_RE = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}\u{23E9}-\u{23F3}\u{FE0F}]/gu;

/** Текст без эмодзи и стрелок-значков, без двойных пробелов. */
export const stripEmoji = (s: string): string => s.replace(EMOJI_RE, '').replace(/\s{2,}/g, ' ').trim();
